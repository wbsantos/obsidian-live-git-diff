/**
 * esbuild.config.mjs — bundle src/*.ts into ../plugin-dist/main.js
 *
 * This file is the direct answer to two bugs the hand-written spike shipped:
 *
 *  1. A relative `require('./mddiff')` that SILENTLY never loaded. Obsidian
 *     evaluates a plugin's main.js without relative-module resolution, so a sibling
 *     file is simply not there. Hand-inlining was the workaround; bundling is the
 *     fix, and it is why every real plugin ships one file.
 *  2. NUL bytes in the emitted JS, which made `grep` treat main.js as BINARY — so
 *     every read-only-invariant grep "passed" without reading a single line. See
 *     tools/check-invariant.mjs, which now asserts UTF-8 + zero NULs explicitly.
 *
 * OUTPUT LAYOUT: sources live in plugin-src/, the loadable plugin is emitted to
 * plugin-dist/ (sibling). plugin-dist/ is what you copy into
 * <vault>/.obsidian/plugins/live-git-diff/ — it contains exactly the three files
 * Obsidian loads and nothing else.
 */
import esbuild from 'esbuild';
import process from 'node:process';
import fs from 'node:fs';
import path from 'node:path';
import builtins from 'builtin-modules';
import { spawnSync } from 'node:child_process';
import { workerViolations } from './tools/worker-security.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD.
If you want to view the source, go to the repository:
https://github.com/jkosturko/obsidian-live-git-diff  (plugin-src/)
*/
`;

const prod = process.argv[2] === 'production';
const outdir = path.resolve('../plugin-dist');

fs.mkdirSync(outdir, { recursive: true });

// Audit the readable worker before embedding it as a Blob in the single plugin bundle.
async function bundleWorker() {
  const result = await esbuild.build({ entryPoints: ['src/diff/worker.ts'], bundle: true, write: false,
    platform: 'browser', format: 'iife', target: 'es2020', minify: false, metafile: true });
  const worker = result.outputFiles[0].text;
  const violations = workerViolations(worker);
  if (violations.length) throw new Error(`Worker capability audit failed: ${violations.join(', ')}`);
  const auditFile = path.resolve('../worker-audit.js');
  fs.writeFileSync(auditFile, worker);
  fs.writeFileSync(path.resolve('../worker-metafile.json'), JSON.stringify(result.metafile, null, 2));
  const check = spawnSync(process.execPath, ['tools/check-invariant.mjs', '--bundle', auditFile], { stdio: 'inherit' });
  if (check.status !== 0) throw new Error('Worker failed the security gate before embedding');
  return { worker, watchFiles: Object.keys(result.metafile.inputs).map(file => path.resolve(file)) };
}

/** Copy the two static files Obsidian loads alongside main.js. */
function copyStatic() {
  for (const f of ['manifest.json', 'styles.css']) {
    fs.copyFileSync(f, path.join(outdir, f));
  }
}

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ['src/main.ts'],
  plugins: [{ name: 'audited-worker', setup(build) {
    build.onResolve({ filter: /^lgd:worker$/ }, () => ({ path: 'worker', namespace: 'lgd' }));
    build.onLoad({ filter: /.*/, namespace: 'lgd' }, async () => {
      const { worker, watchFiles } = await bundleWorker();
      return { contents: `module.exports = ${JSON.stringify(worker)};`, loader: 'js', watchFiles };
    });
  } }],
  bundle: true,
  // `obsidian` and `electron` are provided by the host at runtime; the node builtins
  // are real (this plugin is isDesktopOnly and shells out to git), so they must stay
  // external rather than being bundled or shimmed.
  external: ['obsidian', 'electron', '@codemirror/*', ...builtins],
  format: 'cjs',
  target: 'es2018',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  outfile: path.join(outdir, 'main.js'),
  // MINIFY IS DELIBERATELY OFF, including in production.
  //
  // The read-only invariant is enforced by grepping the BUILT bundle for write
  // methods (tools/check-invariant.mjs). That check is only as trustworthy as the
  // bundle is readable: minified output is still greppable for property names today
  // (esbuild does not mangle properties by default), but it is one flag away from not
  // being — and a security-shaped claim that depends on an unstated default is the
  // same class of mistake as the NUL-byte grep that passed vacuously.
  //
  // An unminified bundle is also auditable by a human, which for a plugin whose whole
  // pitch is "it structurally cannot write to your notes" is worth more than the
  // ~40KB. Cost measured, not assumed: see README "Read-only invariant".
  minify: false,
});

if (prod) {
  await context.rebuild();
  copyStatic();
  await context.dispose();
} else {
  copyStatic();
  // Watch styles.css/manifest.json too: editing a color and seeing nothing change
  // because only main.js is watched is a 20-minute confusion every single time.
  for (const f of ['manifest.json', 'styles.css']) {
    fs.watch(f, () => {
      try {
        copyStatic();
        console.log(`[watch] copied ${f}`);
      } catch (e) {
        console.error(`[watch] copy failed for ${f}`, e);
      }
    });
  }
  await context.watch();
}
